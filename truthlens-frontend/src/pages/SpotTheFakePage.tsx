import { useState, useContext } from 'react'
import { motion, AnimatePresence } from 'framer-motion'
import { Eye, CheckCircle, XCircle, ArrowRight, Trophy, RotateCcw, Lightbulb, Star } from 'lucide-react'
import { ProgressContext } from '../context/ProgressContext'
import { cn } from '../utils/helpers'

const PAGE = {
  initial: { opacity: 0, y: 20 },
  animate: { opacity: 1, y: 0, transition: { duration: 0.5 } },
  exit:    { opacity: 0, y: -20, transition: { duration: 0.3 } },
}

interface Challenge {
  id: number
  question: string
  imageA: string // real
  imageB: string // fake (or vice versa — see fakeIndex)
  fakeIndex: 0 | 1  // which image (A=0, B=1) is fake
  explanation: string
  hints: string[]
  difficulty: 'easy' | 'medium' | 'hard'
  category: string
  realLabel: string
  fakeLabel: string
}

