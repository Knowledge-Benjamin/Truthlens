export default function SpotTheFakePage() {
  const [started,  setStarted]  = useState(false)
  const [current,  setCurrent]  = useState(0)
  const [selected, setSelected] = useState<0 | 1 | null>(null)
  const [score,    setScore]    = useState(0)
  const [answers,  setAnswers]  = useState<boolean[]>([])
  const [showHint, setShowHint] = useState(false)
  const [finished, setFinished] = useState(false)
  const ctx = useContext(ProgressContext)

  const challenge = CHALLENGES[current]
  const total     = CHALLENGES.length
  const isCorrect = selected !== null && selected === challenge.fakeIndex

  const handleSelect = (idx: 0 | 1) => {
    if (selected !== null) return
    setSelected(idx)
    const correct = idx === challenge.fakeIndex
    if (correct) setScore(s => s + 1)
    setAnswers(a => [...a, correct])
  }

  const handleNext = () => {
    if (current + 1 < total) {
      setCurrent(c => c + 1)
      setSelected(null)
      setShowHint(false)
    } else {
      setFinished(true)
      ctx?.recordSpecialBadge?.('spot_trainer')
    }
  }

  const restart = () => {
    setStarted(false); setCurrent(0); setSelected(null)
    setScore(0); setAnswers([]); setShowHint(false); setFinished(false)
  }

  if (!started) return (
    <motion.div {...PAGE} className="min-h-screen pt-20 hero-bg flex items-center">
      <div className="max-w-2xl mx-auto px-4 py-12 text-center w-full">
        <div className="w-20 h-20 rounded-3xl bg-gradient-to-br from-emerald-500 to-teal-600 flex items-center justify-center mx-auto mb-6">
          <Eye size={36} className="text-white" />
        </div>
        <div className="inline-flex items-center gap-2 glass px-4 py-2 rounded-full text-sm text-emerald-300 mb-4 border-emerald-500/30">
          <Eye size={14} /> Spot the Fake Training
        </div>
        <h1 className="font-display font-black text-3xl sm:text-5xl text-white mb-4">
          Can you <span className="gradient-text">Spot the Fake?</span>
        </h1>
        <p className="text-slate-400 text-lg mb-6 max-w-lg mx-auto">
          {total} challenges covering deepfake images, videos, voices, and AI-generated text. Pick the fake in each pair!
        </p>
        <div className="flex items-center justify-center gap-6 mb-8 text-sm text-slate-500">
          <span className="flex items-center gap-1.5"><Star size={14} className="text-warn-400" /> {total} Challenges</span>
          <span className="w-px h-4 bg-slate-700" />
          <span className="flex items-center gap-1.5"><Lightbulb size={14} className="text-brand-400" /> Hints available</span>
          <span className="w-px h-4 bg-slate-700" />
          <span className="flex items-center gap-1.5"><Trophy size={14} className="text-accent-400" /> Earn a badge</span>
        </div>
        <button onClick={() => setStarted(true)} className="btn-primary text-lg px-10 py-4 inline-flex items-center gap-2 group">
          Start Training <ArrowRight size={18} className="group-hover:translate-x-1 transition-transform" />
        </button>
      </div>
    </motion.div>
  )

  if (finished) {
    const pct = Math.round((score / total) * 100)
    return (
      <motion.div {...PAGE} className="min-h-screen pt-20 hero-bg flex items-center">
        <div className="max-w-2xl mx-auto px-4 py-12 text-center w-full">
          <div className="relative w-32 h-32 mx-auto mb-6">
            <svg className="w-full h-full -rotate-90" viewBox="0 0 120 120">
              <circle cx="60" cy="60" r="52" fill="none" stroke="#1e293b" strokeWidth="8"/>
              <motion.circle cx="60" cy="60" r="52" fill="none"
                stroke={pct >= 60 ? '#10b981' : '#f59e0b'} strokeWidth="8" strokeLinecap="round"
                initial={{ pathLength: 0 }} animate={{ pathLength: pct / 100 }}
                transition={{ duration: 1.2, ease: 'easeOut', delay: 0.3 }}
                strokeDasharray="326.7" strokeDashoffset={326.7 - (326.7 * pct / 100)}
              />
            </svg>
            <div className="absolute inset-0 flex flex-col items-center justify-center">
              <Trophy size={26} className={pct >= 60 ? 'text-accent-400' : 'text-warn-400'} />
              <span className="font-display font-black text-3xl text-white mt-1">{pct}%</span>
            </div>
          </div>
          <h2 className="font-display font-bold text-3xl text-white mb-2">
            {pct === 100 ? 'Perfect Spotter! 🎉' : pct >= 60 ? 'Great Eye! 👁️' : 'Keep Practising! 💪'}
          </h2>
          <p className="text-slate-400 mb-2">You spotted <span className="text-white font-bold">{score}</span> out of <span className="text-white font-bold">{total}</span> fakes correctly.</p>
          {pct < 60 && <p className="text-slate-500 text-sm mb-4">Tip: Check our Learning Hub for techniques on spotting deepfakes!</p>}
          <div className="flex items-center justify-center gap-2 mb-8">
            {answers.map((a, i) => (
              <div key={i} className={cn('w-8 h-8 rounded-lg flex items-center justify-center', a ? 'bg-accent-500/20 text-accent-400' : 'bg-danger-500/20 text-danger-400')}>
                {a ? <CheckCircle size={16}/> : <XCircle size={16}/>}
              </div>
            ))}
          </div>
          <div className="flex items-center justify-center gap-3 flex-wrap">
            <button onClick={restart} className="btn-primary flex items-center gap-2">
              <RotateCcw size={16}/> Try Again
            </button>
            <a href="/learn" className="btn-secondary flex items-center gap-2">
              <Eye size={16}/> Learn More
            </a>
          </div>
        </div>
      </motion.div>
    )
  }

  const progress_pct = (current / total) * 100

  return (
    <motion.div {...PAGE} className="min-h-screen pt-20 hero-bg">
      <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8 py-10">
        {/* Progress */}
        <div className="mb-6">
          <div className="flex justify-between text-sm text-slate-400 mb-2">
            <span>Challenge {current + 1} of {total}</span>
            <span className={cn(challenge.difficulty === 'easy' ? 'text-accent-400' : challenge.difficulty === 'medium' ? 'text-warn-400' : 'text-danger-400')}>
              {challenge.difficulty} · {challenge.category}
            </span>
          </div>
          <div className="progress-bar">
            <motion.div className="progress-fill bg-gradient-to-r from-emerald-500 to-teal-500" animate={{ width: `${progress_pct}%` }} transition={{ duration: 0.4 }} />
          </div>
        </div>

        <AnimatePresence mode="wait">
          <motion.div key={current} initial={{ opacity: 0, x: 30 }} animate={{ opacity: 1, x: 0 }} exit={{ opacity: 0, x: -30 }} transition={{ duration: 0.3 }}>
            {/* Question */}
            <h2 className="font-display font-bold text-lg sm:text-2xl text-white mb-6 leading-snug">{challenge.question}</h2>

            {/* Image pair */}
            <div className="grid sm:grid-cols-2 gap-4 mb-6">
              {([challenge.imageA, challenge.imageB] as const).map((img, idx) => {
                const isSelected = selected === idx
                const correct    = idx === challenge.fakeIndex
                const showResult = selected !== null

                return (
                  <button key={idx} onClick={() => handleSelect(idx as 0 | 1)}
                    disabled={selected !== null}
                    className={cn(
                      'relative rounded-2xl overflow-hidden border-2 transition-all duration-200',
                      !showResult && 'border-slate-700 hover:border-brand-500/60 hover:scale-[1.01]',
                      showResult && isSelected && correct && 'border-accent-500 ring-2 ring-accent-500/40',
                      showResult && isSelected && !correct && 'border-danger-500 ring-2 ring-danger-500/40',
                      showResult && !isSelected && correct && 'border-accent-500/40',
                      showResult && !isSelected && !correct && 'border-slate-700 opacity-50',
                    )}>
                    <img src={img} alt={idx === 0 ? 'Option A' : 'Option B'} className="w-full h-48 sm:h-56 object-cover bg-slate-800" />
                    {/* Label overlay */}
                    <div className="absolute bottom-0 left-0 right-0 bg-gradient-to-t from-black/80 to-transparent p-3">
                      <span className="text-white font-bold text-sm">{idx === 0 ? 'A' : 'B'}</span>
                    </div>
                    {/* Result badge */}
                    {showResult && (
                      <div className={cn('absolute top-2 right-2 rounded-full p-1.5', correct ? 'bg-danger-500' : 'bg-accent-500')}>
                        {correct ? <AlertIcon /> : <CheckCircle size={16} className="text-white" />}
                      </div>
                    )}
                  </button>
                )
              })}
            </div>

            {/* Hint */}
            {!selected && (
              <button onClick={() => setShowHint(!showHint)}
                className="flex items-center gap-1.5 text-sm text-brand-400 hover:text-brand-300 mb-4 transition-colors">
                <Lightbulb size={14}/> {showHint ? 'Hide hints' : 'Need a hint?'}
              </button>
            )}
            <AnimatePresence>
              {showHint && !selected && (
                <motion.div initial={{ opacity: 0, height: 0 }} animate={{ opacity: 1, height: 'auto' }} exit={{ opacity: 0, height: 0 }}
                  className="bg-brand-600/10 border border-brand-500/20 rounded-xl p-4 mb-4">
                  <p className="text-brand-300 text-sm font-medium mb-2 flex items-center gap-1.5"><Lightbulb size={13}/> Hints</p>
                  <ul className="space-y-1">
                    {challenge.hints.map((h, i) => (
                      <li key={i} className="text-slate-300 text-sm flex items-start gap-2">
                        <span className="text-brand-400 mt-0.5">•</span>{h}
                      </li>
                    ))}
                  </ul>
                </motion.div>
              )}
            </AnimatePresence>

            {/* Explanation + Next */}
            <AnimatePresence>
              {selected !== null && (
                <motion.div initial={{ opacity: 0, y: 10 }} animate={{ opacity: 1, y: 0 }} className="space-y-4">
                  <div className={cn('rounded-xl p-4 border', isCorrect ? 'bg-accent-500/10 border-accent-500/20' : 'bg-danger-500/10 border-danger-500/20')}>
                    <p className={cn('font-semibold text-sm mb-1 flex items-center gap-1.5', isCorrect ? 'text-accent-300' : 'text-danger-300')}>
                      {isCorrect ? <><CheckCircle size={14}/> Correct! That's the fake.</> : <><XCircle size={14}/> Not quite — the fake was {challenge.fakeIndex === 0 ? 'A' : 'B'}.</>}
                    </p>
                    <p className="text-slate-400 text-sm leading-relaxed">{challenge.explanation}</p>
                    <p className="text-slate-500 text-xs mt-2">
                      A = <span className="text-slate-300">{challenge.realLabel}</span> · B = <span className="text-slate-300">{challenge.fakeLabel}</span>
                    </p>
                  </div>
                  <button onClick={handleNext} className="btn-primary w-full flex items-center justify-center gap-2">
                    {current + 1 < total ? 'Next Challenge' : 'See Results'}
                    <ArrowRight size={16}/>
                  </button>
                </motion.div>
              )}
            </AnimatePresence>
          </motion.div>
        </AnimatePresence>
      </div>
    </motion.div>
  )
}

function AlertIcon() {
  return (
    <svg width="16" height="16" viewBox="0 0 16 16" fill="none">
      <path d="M8 1L15 13H1L8 1Z" fill="white" stroke="none"/>
      <path d="M8 6V9" stroke="#dc2626" strokeWidth="1.5" strokeLinecap="round"/>
      <circle cx="8" cy="11" r="0.75" fill="#dc2626"/>
    </svg>
  )
}
